import json
import time

from advanced_rag import config, vectorstore
from advanced_rag.chunking import Chunk
from advanced_rag.retrieval.bm25 import BM25Index
from advanced_rag.retrieval.hybrid import hybrid_search

QUESTIONS_FILE = config.ROOT / "eval" / "questions.json"
RESULTS_FILE = config.ROOT / "eval" / "results.md"


def load_questions() -> list[dict]:
    # each item: question, relevant (phrases that a chunk answering it contains; null = not answerable),
    # answer_contains (any of these words in the answer counts as correct)
    return json.loads(QUESTIONS_FILE.read_text(encoding="utf-8"))


# ---------- retrieval: did search find the right chunk? (no LLM, fast, free) ----------

def first_relevant_rank(hits: list[tuple[float, Chunk]], relevant: list[str]) -> int | None:
    # the position (1, 2, 3, ...) of the first retrieved chunk that contains any of the phrases
    for rank, (_, chunk) in enumerate(hits, start=1):
        if any(phrase in chunk.text for phrase in relevant):
            return rank
    return None


def retrieval_scores(ranks: list[int | None], k: int = 3) -> dict:
    # hit rate @k: how often the right chunk is somewhere in the top k
    # MRR (mean reciprocal rank): 1st place = 1, 2nd = 1/2, 3rd = 1/3, missed = 0, then averaged
    hits = [r is not None and r <= k for r in ranks]
    reciprocal = [1 / r if r is not None else 0 for r in ranks]
    return {"hit_rate": sum(hits) / len(ranks), "mrr": sum(reciprocal) / len(ranks)}


def evaluate_retrieval(
    collection, bm25: BM25Index, questions: list[dict], k: int = 3, include_rewrite: bool = False
) -> dict:
    from advanced_rag.rag import retrieve

    methods = {
        "semantic": lambda q: vectorstore.search(collection, q, 10),
        "bm25": lambda q: bm25.search(q, 10),
        "hybrid": lambda q: hybrid_search(collection, bm25, q, k=10),
        "hybrid+rerank": lambda q: retrieve(q, collection, bm25, k=10),
    }
    if include_rewrite:  # costs one real LLM call per question
        methods["+rewrite"] = lambda q: retrieve(q, collection, bm25, k=10, rewrite_query=True)

    answerable = [q for q in questions if q["relevant"]]
    report = {}
    for name, search in methods.items():
        start = time.perf_counter()
        ranks = [first_relevant_rank(search(q["question"]), q["relevant"]) for q in answerable]
        report[name] = retrieval_scores(ranks, k)
        report[name]["ms"] = (time.perf_counter() - start) * 1000 / len(answerable)  # average per question
    return report


# ---------- answers: did the LLM say the right thing? (real LLM calls, slower) ----------

def is_correct(answer: str, answer_contains: list[str]) -> bool:
    text = answer.lower().replace("’", "'")  # some models write a curly apostrophe in "don’t"
    return any(expected in text for expected in answer_contains)


def evaluate_answers(collection, bm25: BM25Index, questions: list[dict]) -> list[dict]:
    from advanced_rag.rag import answer

    results = []
    for q in questions:
        reply = answer(q["question"], collection, bm25, use_cache=False).text
        results.append({
            "question": q["question"],
            "answerable": q["relevant"] is not None,
            "correct": is_correct(reply, q["answer_contains"]),
            "cited": "#" in reply and "[" in reply,  # mentions a chunk id like [cat.txt#25]
            "answer": reply,
        })
    return results


def report_markdown(retrieval: dict, answers: list[dict] | None) -> str:
    # the same numbers as the terminal, as a markdown file you can commit and compare against later
    lines = [
        "# Evaluation results",
        "",
        f"Generated by `uv run python -m advanced_rag.evaluate --answers --rewrite --save` "
        f"with `{config.EMBEDDING_MODEL}` and the questions in `eval/questions.json`.",
        "",
        "## Retrieval (answerable questions, top 3)",
        "",
        "| Method | Hit rate @3 | MRR | ms / question |",
        "|---|---|---|---|",
    ]
    lines += [f"| {n} | {s['hit_rate']:.0%} | {s['mrr']:.2f} | {s['ms']:.0f} |" for n, s in retrieval.items()]
    if answers:
        answerable = [r for r in answers if r["answerable"]]
        refusals = [r for r in answers if not r["answerable"]]
        lines += [
            "",
            "## Answers (hybrid + rerank, real LLM, cache off)",
            "",
            "| Check | Score |",
            "|---|---|",
            f"| Correct | {sum(r['correct'] for r in answerable)}/{len(answerable)} |",
            f"| Cited a chunk | {sum(r['cited'] for r in answerable)}/{len(answerable)} |",
            f"| Said \"I don't know\" when it should | {sum(r['correct'] for r in refusals)}/{len(refusals)} |",
            "",
            "## Every answer",
            "",
            "| | Question | Answer |",
            "|---|---|---|",
        ]
        for r in answers:
            text = " ".join(r["answer"].split()).replace("|", "\\|")
            lines.append(f"| {'✅' if r['correct'] else '❌'} | {r['question']} | {text} |")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    import sys

    collection = vectorstore.get_collection()
    bm25 = BM25Index(vectorstore.all_chunks(collection))
    questions = load_questions()

    retrieval = evaluate_retrieval(collection, bm25, questions, include_rewrite="--rewrite" in sys.argv)
    print(f"Retrieval ({sum(1 for q in questions if q['relevant'])} answerable questions, top 3)")
    for name, scores in retrieval.items():
        print(f"  {name:14} hit rate {scores['hit_rate']:.0%}   MRR {scores['mrr']:.2f}   {scores['ms']:.0f} ms/question")

    results = None
    if "--answers" in sys.argv:
        results = evaluate_answers(collection, bm25, questions)
        answerable = [r for r in results if r["answerable"]]
        refusals = [r for r in results if not r["answerable"]]
        print(f"\nAnswers ({len(results)} LLM calls)")
        print(f"  correct      {sum(r['correct'] for r in answerable)}/{len(answerable)}")
        print(f"  cited        {sum(r['cited'] for r in answerable)}/{len(answerable)}")
        print(f"  said I don't know when it should  {sum(r['correct'] for r in refusals)}/{len(refusals)}")
        for r in results:
            if not r["correct"]:
                print(f"  ✗ {r['question']}\n      {r['answer'].strip()[:200]}")

    if "--save" in sys.argv:
        RESULTS_FILE.write_text(report_markdown(retrieval, results), encoding="utf-8")
        print(f"\nsaved {RESULTS_FILE}")
